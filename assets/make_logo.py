"""Redraws the Agesen EL-Teknik logo in two colours, based on the supplied image.

Run: python assets/make_logo.py  -> assets/logo-light.png (white text, for dark
backgrounds) and assets/logo-dark.png (black text, for light backgrounds).
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

RED = (218, 54, 72, 255)
FONT = r"C:\Windows\Fonts\ariblk.ttf"
H = 400            # letter height in px before stretching
STRETCH = 1.42     # the logo font is wide; Arial Black is stretched horizontally
OUT = Path(__file__).parent


def word(text, color):
    f = ImageFont.truetype(FONT, int(H * 1.38))
    l, t, r, b = f.getbbox(text)
    im = Image.new("RGBA", (r - l, b - t), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((-l, -t), text, font=f, fill=color)
    return im.resize((int(im.width * STRETCH), im.height), Image.LANCZOS)


def logo(ink):
    l1 = word("AGESEN", ink)
    el, tek = word("EL", ink), word("TEKNIK", ink)
    gap = int(H * 0.10)
    dash_w, dash_h = int(H * 0.42), int(H * 0.30)
    l2w = el.width + gap + dash_w + gap + tek.width
    dot = int(l1.height * 1.10)
    width = max(l1.width + int(dot * 0.62), l2w)
    lead = int(H * 0.22)
    height = l1.height + lead + tek.height
    pad = int(H * 0.12)
    im = Image.new("RGBA", (width + 2 * pad, height + 2 * pad + int(dot * 0.1)), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    y1 = pad + int(dot * 0.1)
    # Red dot behind and to the right of the N, slightly above the line as in the original
    cx = pad + l1.width + int(dot * 0.12)
    cy = y1 + l1.height / 2 - dot * 0.08
    d.ellipse((cx - dot / 2, cy - dot / 2, cx + dot / 2, cy + dot / 2), fill=RED)
    im.alpha_composite(l1, (pad, y1))
    y2 = y1 + l1.height + lead
    x = pad
    im.alpha_composite(el, (x, y2 + tek.height - el.height))
    x += el.width + gap
    dy = y2 + tek.height - int(H * 0.36) - dash_h // 2
    d.rectangle((x, dy, x + dash_w, dy + dash_h), fill=RED)
    x += dash_w + gap
    im.alpha_composite(tek, (x, y2))
    return im


for name, ink in (("logo-light.png", (255, 255, 255, 255)), ("logo-dark.png", (12, 12, 12, 255))):
    logo(ink).save(OUT / name)
    print(name)


# Embedded in the program, so the company bar cannot be changed by replacing a file.
import base64, io  # noqa: E402
small = logo((255, 255, 255, 255))
small.thumbnail((small.width, 160), Image.LANCZOS)
buf = io.BytesIO()
small.save(buf, "PNG", optimize=True)
data = base64.b64encode(buf.getvalue()).decode("ascii")
lines = [data[i:i + 100] for i in range(0, len(data), 100)]
target = OUT.parent / "camview" / "brand_logo.py"
target.write_text('"""Generated by assets/make_logo.py. Do not edit by hand."""\n\nLOGO_PNG_B64 = (\n'
                  + "".join(f'    "{line}"\n' for line in lines) + ")\n", encoding="utf-8")
print(target.name, len(buf.getvalue()), "bytes")
